// Builds prisma/migrations/0_baseline/migration.sql — the plain-PostgreSQL
// schema — from a schema-only dump of the Supabase `public` schema:
//   docker exec supabase_db_WhatsApp-CRM-YT pg_dump -U postgres --schema-only \
//     --schema=public --no-owner --no-privileges postgres > public.sql
//   node scripts/postgres/build-baseline.mjs public.sql
// What changes vs. Supabase:
//   - auth.users → public.users (own table, plus Better Auth tables)
//   - auth.uid() → public.app_user_id() (session setting app.user_id)
//   - request.headers x-workspace-id → setting app.workspace_id
//   - no RLS / policies (tenant isolation is enforced in the server)
//   - extensions.* → core gen_random_uuid() / public.unaccent
//   - the signup trigger moves from auth.users to public.users
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'

const src = process.argv[2]
if (!src) throw new Error('usage: node build-baseline.mjs <public.sql>')
let sql = readFileSync(src, 'utf8')

// Drop psql meta commands, the search_path reset, and the CREATE SCHEMA public.
sql = sql
  .split('\n')
  .filter((l) => !l.startsWith('\\restrict') && !l.startsWith('\\unrestrict'))
  .join('\n')
  .replace("SELECT pg_catalog.set_config('search_path', '', false);\n", '')
  .replace(/^CREATE SCHEMA public;\n/m, '')
  .replace(/^COMMENT ON SCHEMA public IS .*;\n/m, '')

// Policies and RLS switches.
sql = sql.replace(/^CREATE POLICY [\s\S]*?;\n/gm, '')
sql = sql.replace(/^ALTER TABLE (ONLY )?\S+ ENABLE ROW LEVEL SECURITY;\n/gm, '')
sql = sql.replace(/^ALTER TABLE (ONLY )?\S+ FORCE ROW LEVEL SECURITY;\n/gm, '')

// Supabase auth / request context.
sql = sql.replaceAll('auth.uid()', 'public.app_user_id()')
sql = sql.replaceAll('auth.users', 'public.users')
sql = sql.replace(
  "NULLIF(current_setting('request.headers', true), '')::json ->> 'x-workspace-id'",
  "NULLIF(current_setting('app.workspace_id', true), '')",
)

// Extensions live in public on a plain server.
sql = sql.replaceAll('extensions.uuid_generate_v4()', 'gen_random_uuid()')
sql = sql.replaceAll("extensions.unaccent('extensions.unaccent'::regdictionary", "public.unaccent('public.unaccent'::regdictionary")
sql = sql.replaceAll("SET search_path TO 'public', 'extensions'", "SET search_path TO 'public'")

// The platform-admin flag is only written by the server now.
sql = sql.replace(/^CREATE TRIGGER protect_platform_admin [^\n]*\n/m, '')
sql = sql.replace(/^CREATE FUNCTION public\.protect_platform_admin\(\)[\s\S]*?\n\$\$;\n/m, '')

// Storage-only helper (Supabase Storage policies) is gone.
sql = sql.replace(/^CREATE FUNCTION public\.can_access_ws_object\(object_name text\)[\s\S]*?\n\$\$;\n/m, '')
// Reports RPCs: the server checks the role before calling them.
sql = sql.replace(
  /(CREATE FUNCTION public\.reports_guard\(p_ws uuid\) RETURNS void\n    LANGUAGE plpgsql STABLE\n    AS \$\$\n)BEGIN[\s\S]*?END;\n\$\$;/,
  '$1BEGIN\n  -- Tenant and role checks happen in the server (no database roles per user).\n  RETURN;\nEND;\n$$$$;',
)

const leftovers = ['auth.', 'extensions.', 'request.jwt', 'request.headers', 'storage.', 'supabase_']
  .map((k) => [k, sql.split(k).length - 1])
  .filter(([, n]) => n > 0)
if (leftovers.length) console.warn('Supabase references left:', leftovers)

const head = `-- Baseline schema for plain PostgreSQL (generated by scripts/postgres/build-baseline.mjs).
CREATE EXTENSION IF NOT EXISTS unaccent WITH SCHEMA public;

-- Who is acting, for triggers that record an actor. The server sets it
-- per transaction (SET LOCAL app.user_id = '...'); NULL otherwise.
CREATE FUNCTION public.app_user_id() RETURNS uuid
    LANGUAGE sql STABLE
    AS $$ SELECT NULLIF(current_setting('app.user_id', true), '')::uuid $$;

-- Accounts (Better Auth tables, snake_case; mapped in prisma/schema.prisma).
CREATE TABLE public.users (
    id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
    email text NOT NULL UNIQUE,
    name text NOT NULL DEFAULT '',
    email_verified boolean NOT NULL DEFAULT false,
    image text,
    -- Signup data (full_name, business_name, business_type, invite…), read by handle_new_user.
    meta jsonb NOT NULL DEFAULT '{}'::jsonb,
    banned boolean NOT NULL DEFAULT false,
    last_sign_in_at timestamp with time zone,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now()
);
CREATE TABLE public.auth_sessions (
    id text PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    token text NOT NULL UNIQUE,
    expires_at timestamp with time zone NOT NULL,
    ip_address text,
    user_agent text,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now()
);
CREATE INDEX idx_auth_sessions_user ON public.auth_sessions(user_id);
CREATE TABLE public.auth_accounts (
    id text PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    account_id text NOT NULL,
    provider_id text NOT NULL,
    access_token text,
    refresh_token text,
    id_token text,
    access_token_expires_at timestamp with time zone,
    refresh_token_expires_at timestamp with time zone,
    scope text,
    -- bcrypt hash (migrated from Supabase) or Better Auth's own format
    password text,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now()
);
CREATE INDEX idx_auth_accounts_user ON public.auth_accounts(user_id);
CREATE TABLE public.auth_verifications (
    id text PRIMARY KEY,
    identifier text NOT NULL,
    value text NOT NULL,
    expires_at timestamp with time zone NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now()
);
CREATE INDEX idx_auth_verifications_identifier ON public.auth_verifications(identifier);
`

const tail = `
-- Signup: profile + own workspace (was a trigger on auth.users).
CREATE TRIGGER on_user_created AFTER INSERT ON public.users FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();
`

sql = sql.replace('COALESCE(NEW.raw_user_meta_data, \'{}\'::jsonb)', 'COALESCE(NEW.meta, \'{}\'::jsonb)')

const out = 'prisma/migrations/0_baseline/migration.sql'
mkdirSync('prisma/migrations/0_baseline', { recursive: true })
writeFileSync(out, head + '\n' + sql + tail)
writeFileSync('prisma/migrations/migration_lock.toml', 'provider = "postgresql"\n')
console.log(`wrote ${out}`)
