// Writes src/lib/db/schema-meta.ts from prisma/schema.prisma: per model,
// the fields that need conversion (date, timestamp, decimal, bigint) and
// relation fields → target model. Run after `prisma db pull`:
//   node scripts/postgres/gen-schema-meta.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const schema = readFileSync('prisma/schema.prisma', 'utf8')
const models = [...schema.matchAll(/^model (\w+) \{([\s\S]*?)^\}/gm)]
const names = new Set(models.map((m) => m[1]))
const meta = {}
for (const [, model, body] of models) {
  const fields = {}
  for (const line of body.split('\n')) {
    const m = /^\s+(\w+)\s+(\w+)(\?|\[\])?\s*(.*)$/.exec(line)
    if (!m || line.trim().startsWith('@@')) continue
    const [, name, type, , attrs] = m
    if (names.has(type)) fields[name] = { rel: type }
    else if (type === 'DateTime') fields[name] = /@db\.Date\b/.test(attrs) ? 'date' : 'timestamp'
    else if (type === 'Decimal') fields[name] = 'decimal'
    else if (type === 'BigInt') fields[name] = 'bigint'
  }
  meta[model] = fields
}
const out = `// Generated by scripts/postgres/gen-schema-meta.mjs — do not edit.
export type FieldKind = 'date' | 'timestamp' | 'decimal' | 'bigint' | { rel: string }
export const SCHEMA_META: Record<string, Record<string, FieldKind>> = ${JSON.stringify(meta, null, 2)}
`
writeFileSync('src/lib/db/schema-meta.ts', out)
console.log(`schema-meta: ${Object.keys(meta).length} models`)

// Result extension: same value shapes as PostgREST, with matching types.
const nullable = new Map()
for (const [, model, body] of models) {
  for (const line of body.split('\n')) {
    const m = /^\s+(\w+)\s+(\w+)(\?)?/.exec(line)
    if (m) nullable.set(`${model}.${m[1]}`, m[3] === '?')
  }
}
const conv = {
  timestamp: (v) => `${v}.toISOString()`,
  date: (v) => `${v}.toISOString().slice(0, 10)`,
  decimal: (v) => `${v}.toNumber()`,
  bigint: (v) => `Number(${v})`,
}
const blocks = []
for (const [model, fields] of Object.entries(meta)) {
  const entries = Object.entries(fields).filter(([, k]) => typeof k === 'string')
  if (!entries.length) continue
  const lines = entries.map(([f, k]) => {
    const v = `r.${f}`
    const expr = nullable.get(`${model}.${f}`) ? `${v} === null ? null : ${conv[k](v)}` : conv[k](v)
    return `      ${f}: { needs: { ${f}: true }, compute: (r) => ${expr} },`
  })
  blocks.push(`    ${model}: {\n${lines.join('\n')}\n    },`)
}
writeFileSync(
  'src/lib/db/result-compat.ts',
  `// Generated by scripts/postgres/gen-schema-meta.mjs — do not edit.
// Rows come back like they did from Supabase/PostgREST: timestamps as ISO
// strings, DATE as 'YYYY-MM-DD', NUMERIC and BIGINT as numbers.
import { Prisma } from '@/generated/prisma/client'

export const resultCompat = Prisma.defineExtension({
  name: 'result-compat',
  result: {
${blocks.join('\n')}
  },
})
`,
)
console.log('result-compat written')
